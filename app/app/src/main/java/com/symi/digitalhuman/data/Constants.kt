package com.symi.digitalhuman.data

/**
 * 最短有效段时长（毫秒）。
 *
 * 单一事实源：VAD 落盘（CaptureService）、回放列表（observePlayable）、
 * 小时统计（AggregateWorker）、上传前清理（DailyUploadWorker）四处全部引用它。
 * 曾经它被硬编码成两份（Kotlin 常量 + SQL 字面量 2200），改一处漏一处就会出现
 * 「回放列表里有这条、统计里没有」的静默不一致，因此提到这里作为 const val，
 * 供 Room 的 @Query 字符串模板在编译期折叠。
 */
const val MIN_SEGMENT_MS = 2200L

/** 声纹注册样本时长（秒）。UI 进度与录音逻辑共用，避免两边各写一份 30。 */
const val ENROLL_SECONDS = 30

/**
 * 声纹注册时朗读的固定文本（约 130 字，正常语速读完 30 秒左右）。
 *
 * 为什么要固定文本：声纹注册样本必须可比——同一个人每次读同样的内容，
 * 提取出的 embedding 才稳定；也让不同的人之间差异主要来自声线而不是内容。
 * 文本本身刻意覆盖日常对话里高频出现的声韵母、数字与常用词，
 * 而不是随便一段散文，这样注册后的匹配在真实工作会议里更准。
 *
 * 展示给用户时原样显示，UI 不改写、不截断——录音与文本必须一一对应。
 *
 * ⚠️ 服务端有一份同样的文本（`server/app/voiceprint.py` 的 `ENROLL_SCRIPT`，
 *    经 `/api/console/state` 的 `enroll.script` 下发给 Mac 壳与网页工作台）。
 *    Android 端不能改成从服务端拉：注册样本走 EnrollQueue 补交，断网时也要能录，
 *    本地必须留一份。**改这里的文本就要同步改服务端那一份**——两边不一致会导致
 *    「手机录的样本」与「电脑上传的样本」内容不同，锚点可比性下降。
 */
const val ENROLL_SCRIPT = "今天是九月四号，星期四。我现在读一段固定的文字，用来登记我的声音。\n" +
    "早晨出门的时候，天有点阴，风从窗口吹进来，桌上的纸轻轻翻动。\n" +
    "我喜欢在安静的房间里工作，偶尔喝一口温水，看看窗外的树。\n" +
    "下午要和同事讨论设备的安装位置，先准备好工具，再确认一遍清单。\n" +
    "这段话不长，但包含了日常说话里常用的字词，读完刚好三十秒。"
